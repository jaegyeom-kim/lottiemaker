// 경량 i18n — 한국어 원문이 키, 영어는 사전 조회. 미번역 문자열은 한국어로 폴백.
// 언어 전환 시 App 루트가 key={lang}로 통째 리마운트되므로 t()는 모듈 변수만 읽으면 된다.
export type Lang = 'ko' | 'en'

const KEY = 'lottiemaker.lang'

let current: Lang = (() => {
  try {
    return localStorage.getItem(KEY) === 'en' ? 'en' : 'ko'
  } catch {
    return 'ko'
  }
})()

export function getLang(): Lang {
  return current
}

export function setLangValue(l: Lang) {
  current = l
  try {
    localStorage.setItem(KEY, l)
  } catch {
    // 저장 실패 — 이번 세션만 적용
  }
  try {
    document.documentElement.lang = l
  } catch {
    // SSR/테스트 환경 — 무시
  }
}

